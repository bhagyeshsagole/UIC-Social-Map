import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const feed=JSON.parse(readFileSync(new URL('../public/campus-events.json',import.meta.url)));
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',message=>{if(message.type()==='error'&&/fill-extrusion|expression|event_venues/i.test(message.text()))errors.push(message.text());});
const pose=async()=>JSON.parse(await page.locator('.map').getAttribute('data-camera'));
try{
  await page.clock.setFixedTime(new Date(feed.fetchedAt));
  await page.route('**/api/campus-events',route=>route.fulfill({json:feed}));
  await page.goto('http://127.0.0.1:5173');
  await page.waitForFunction(()=>document.querySelector('.map')?.dataset.eventVenues,{},{timeout:30000});
  assert.ok(!JSON.parse(await page.locator('.map').getAttribute('data-event-venues')).includes('uic-0605'),'UIC buildings retain red; purple is reserved for off-campus venues');
  await page.screenshot({path:'artifacts/event-buildings.png'});
  // Hovering an event building previews its events; clicking opens that building's events.
  let hit=null;
  scan: for(let y=180;y<900;y+=22)for(let x=200;x<1300;x+=22){await page.mouse.move(x,y);if(await page.locator('.building-peek').count()){hit=[x,y];break scan;}}
  assert.ok(hit,'an event building shows an event preview on hover');
  assert.match(await page.locator('.building-peek').innerText(),/upcoming events?[\s\S]*Click to explore/);
  await page.screenshot({path:'artifacts/building-peek.png'});
  await page.mouse.click(...hit);
  const building=page.getByRole('complementary',{name:'Events in this building'});
  await building.waitFor();
  assert.ok(await building.locator('.campus-event-card').count()>0);
  assert.ok(await page.locator('.map').getAttribute('data-focused-venue'));
  await page.waitForTimeout(1000);
  await page.screenshot({path:'artifacts/building-events.png'});
  await page.getByRole('button',{name:'Close building events'}).click();
  await page.getByRole('button',{name:'Live events',exact:true}).click();
  await page.getByRole('searchbox',{name:'Search UIC events'}).fill('Andersen Firm Night');
  await page.getByRole('button',{name:'Show Andersen Firm Night on map',exact:true}).click();
  await page.getByRole('region',{name:'Selected event on map'}).waitFor();
  await page.waitForTimeout(1300);
  assert.equal(await page.locator('.has-live-events').count(),0,'large sheet closes to reveal building');
  let camera=await pose();
  assert.ok(Math.abs(camera.center[0]+87.647964)<.00001&&Math.abs(camera.center[1]-41.871967)<.00001);
  assert.ok(camera.zoom>=17&&camera.pitch>40);
  assert.equal(await page.locator('.event-building-marker span').innerText(),'UIC Student Center East');
  assert.ok(!JSON.parse(await page.locator('.map').getAttribute('data-event-venues')).includes('uic-0605'));
  await page.screenshot({path:'artifacts/event-building-focus.png'});
  await page.getByRole('button',{name:'Back to events',exact:true}).click();
  const input=page.getByRole('searchbox',{name:'Search UIC events'});
  await input.fill('Commuter Connect');
  const first=page.locator('.campus-events .has-map-event').first();
  const registration=first.getByRole('link',{name:'Details & registration'});
  assert.match(await registration.getAttribute('href'),/^https:\/\/uic.campusgroups.com\//);
  await first.locator('.campus-organizer').click();
  await page.waitForTimeout(1200);
  assert.equal(await page.locator('.map').getAttribute('data-focused-event-venue'),'uic-0605','clicking card body navigates too');
  await page.getByRole('button',{name:'Back to events',exact:true}).click();
  await page.getByRole('group',{name:'Event categories'}).getByRole('button',{name:'Off-campus',exact:true}).click();
  await page.getByRole('button',{name:'Show Mary Cassatt: After Impressionism on map'}).click();
  await page.waitForFunction(()=>document.querySelector('.map')?.dataset.eventBuildings?.includes('|art-institute|'),{},{timeout:30000});
  assert.equal(await page.locator('.map').getAttribute('data-focused-event-venue'),'art-institute');
  await page.getByRole('button',{name:'Back to events',exact:true}).click();
  await page.getByRole('searchbox',{name:'Search UIC events'}).fill('Chicago Marathon');
  await page.getByRole('button',{name:'Show Chicago Marathon on map',exact:true}).click();
  await page.waitForTimeout(1100);
  assert.match(await page.getByRole('region',{name:'Selected event on map'}).innerText(),/Chicago Marathon/);
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Back to events',exact:true}).click();
  await page.getByRole('searchbox',{name:'Search UIC events'}).fill('Andersen Firm Night');
  await page.getByRole('button',{name:'Show Andersen Firm Night on map',exact:true}).click();
  await page.waitForTimeout(1200);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'artifacts/event-building-mobile.png'});
  // A later same-month feed with no remaining events removes event color at UIC.
  await page.unroute('**/api/campus-events');
  const empty={...feed,fetchedAt:'2026-10-06T00:00:00Z',events:[]};
  await page.route('**/api/campus-events',route=>route.fulfill({json:empty}));
  await page.reload();
  await page.waitForFunction(()=>{const ids=document.querySelector('.map')?.dataset.eventVenues;return ids&&!JSON.parse(ids).includes('uic-0605');});
  await page.clock.setFixedTime(new Date('2026-10-06T03:00:00Z'));
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('.app.night')&&document.querySelector('.map')?.dataset.eventVenues);
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:'artifacts/event-buildings-night.png'});
  assert.deepEqual(errors,[]);
  console.log('Event map: off-campus purple footprints, card/title navigation, registration links, off-campus/outdoor, mobile, feed removal and night restyle passed.');
}finally{await browser.close();}
