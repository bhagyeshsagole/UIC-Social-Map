import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {upcomingCampusEvents} from '../src/campusEvents.js';

const feed = JSON.parse(readFileSync(new URL('../public/campus-events.json', import.meta.url)));
const now = new Date(feed.fetchedAt), expected = upcomingCampusEvents(feed.events, now);
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}, timezoneId:'Asia/Tokyo'});
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.clock.setFixedTime(now);
  await page.route('**/api/campus-events', route => route.fulfill({json:feed}));
  await page.goto((process.env.TEST_APP_URL||'http://127.0.0.1:5173'));
  await page.getByRole('button', {name:'Live events', exact:true}).click();
  await page.locator('.campus-events .campus-event-card').first().waitFor();
  assert.equal(await page.locator('.campus-events .campus-event-card').count(), expected.length);
  const heading = await page.locator('.campus-events').innerText();
  assert.match(heading, new RegExp(`${expected.length} upcoming events`));
  for (const gone of ['October 2026 at UIC', 'Chicago time', 'From UIC Connection', 'Checked']) assert.ok(!heading.includes(gone), gone);
  await page.getByRole('button', {name:'Pick a date'}).click();
  const picker = page.getByRole('dialog', {name:'Pick a date'});
  assert.equal(await picker.getByRole('button', {name:'Previous month'}).isDisabled(), true, 'no months before the current one');
  const firstMonth = await picker.locator('.date-picker-month span').innerText();
  await picker.getByRole('button', {name:'Next month'}).click();
  assert.notEqual(await picker.locator('.date-picker-month span').innerText(), firstMonth, 'next month is reachable');
  assert.ok(await picker.locator('.date-picker-grid button:not([disabled])').count() > 0, 'next month offers event days');
  await picker.getByRole('button', {name:'Previous month'}).click();
  const day = picker.locator('.date-picker-grid button:not([disabled])').first();
  const count = Number((await day.getAttribute('aria-label')).match(/, (\d+) event/)[1]);
  await day.click();
  assert.equal(await page.locator('.event-results .campus-event-card').count(), count, 'a picked date shows only that day across UIC events and exhibitions');
  assert.match(await page.locator('.campus-heading').innerText(), / on [A-Z][a-z]{2}, [A-Z][a-z]{2} \d+/);
  await page.getByRole('button', {name:'Clear date'}).click();
  assert.equal(await page.locator('.campus-events .campus-event-card').count(), expected.length);
  assert.match(await page.locator('.campus-event-date').first().innerText(), / CT$/);
  for (const e of [expected.find(e => e.hasPublicLocation), expected.find(e => !e.hasPublicLocation)]) {
    await page.getByRole('searchbox', {name:'Search UIC events'}).fill(e.title);
    const card = page.locator('.campus-events .campus-event-card').first();
    assert.equal(await card.getByRole('link', {name:'Details & registration'}).getAttribute('href'), e.url);
    assert.equal(await card.getByRole('link', {name:e.hasPublicLocation ? 'Maps' : 'View location', exact:true}).getAttribute('href'), e.locationUrl);
  }
  await page.getByRole('searchbox', {name:'Search UIC events'}).fill('no-such-event-abcdef');
  await page.getByRole('heading', {name:'No matching events'}).waitFor();
  await page.getByRole('searchbox', {name:'Search UIC events'}).fill('');
  const sheet = await page.locator('.has-live-events').boundingBox();
  assert.ok(sheet.width >= 1100 && sheet.height >= 700, 'Live events has a larger desktop sheet');
  const tags = page.getByRole('group', {name:'Event categories'});
  assert.equal(await tags.locator('button[aria-pressed]').count(), 4, 'For you plus three category tags');
  assert.equal(await tags.getByRole('button', {name:'Pick a date'}).count(), 1, 'date filter sits in the category row');
  await tags.getByRole('button', {name:'Off-campus', exact:true}).click();
  await page.getByRole('heading', {name:'Around the city'}).waitFor();
  assert.equal(await page.locator('.campus-events').count(), 0);
  assert.ok(await page.locator('.venue-event-card').count() > 0);
  assert.equal(await page.getByRole('region', {name:'Off-campus events'}).getByText('Gallery 400', {exact:true}).count(), 0, 'UIC gallery is not classified as independent');
  await tags.getByRole('button', {name:'Community', exact:true}).click();
  await page.getByRole('heading', {name:'No public events yet.'}).waitFor();
  assert.equal(await page.locator('.campus-event-card').count(), 0, 'Private drafts are not published community events');
  await page.getByRole('button', {name:'View My Events', exact:true}).click();
  await page.getByRole('heading', {name:'My Events', exact:true}).waitFor();
  await page.getByRole('button', {name:'Live events', exact:true}).click();
  await tags.getByRole('button', {name:'UIC', exact:true}).click();
  assert.equal(await tags.getByRole('button', {name:'UIC', exact:true}).getAttribute('aria-pressed'), 'true');
  await page.screenshot({path:'artifacts/live-events.png'});
  await page.getByRole('button', {name:'Search everything', exact:true}).click();
  await page.getByRole('combobox', {name:'Search everything'}).fill(expected[0].title);
  await page.getByRole('option').first().waitFor();
  assert.match(await page.getByRole('option').first().innerText(), / CT/);
  await page.keyboard.press('Escape');
  await page.evaluate(() => document.activeElement?.blur());
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(() => scrollY === 80, null, {timeout:5000});
  const mobileSheet = await page.locator('.has-live-events').boundingBox();
  // Phone: the sheet sits below the top row (legend, count, account) and above the bottom nav.
  assert.ok(mobileSheet.height > 600 && mobileSheet.y >= 54 && mobileSheet.y + mobileSheet.height <= 844 - 66, JSON.stringify(mobileSheet));
  await tags.getByRole('button', {name:'Off-campus', exact:true}).click();
  await page.getByRole('heading', {name:'Around the city'}).waitFor();
  await tags.getByRole('button', {name:'UIC', exact:true}).click();
  await page.screenshot({path:'artifacts/live-events-mobile.png'});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.ok(await page.locator('.campus-events .campus-event-card').first().evaluate(e => e.getBoundingClientRect().right <= innerWidth));
  await page.unroute('**/api/campus-events');
  await page.route('**/api/campus-events', route => route.fulfill({status:503, json:{error:'Unavailable'}}));
  // No refresh button: a reload re-requests the feed and falls back to the saved snapshot.
  await page.reload();
  await page.getByRole('button', {name:'Live events', exact:true}).click();
  await page.getByText('Showing saved listings; live refresh unavailable.').waitFor();
  assert.equal(await page.locator('.campus-events .campus-event-card').count(), expected.length);
  await page.clock.setFixedTime(new Date(Math.max(...feed.events.map(e => Date.parse(e.end))) + 1000));
  // Reload initializes the app clock at the new time; cached records cannot revive past events.
  await page.reload();
  await page.getByRole('button', {name:'Live events', exact:true}).click();
  await page.getByRole('heading', {name:'No upcoming UIC events to show'}).waitFor();
  assert.equal(await page.locator('.campus-events .campus-event-card').count(), 0);
  await page.route('**/campus-events.json', route => route.fulfill({status:404}));
  await page.reload();
  await page.getByRole('button', {name:'Live events', exact:true}).click();
  await page.getByText('UIC Connection is unavailable. Open the UIC calendar for listings.').waitFor();
  assert.equal(errors.length, 0, errors.join('\n'));
  console.log('Campus events: desktop/mobile, CT times, search, official links, fallback, expiry, and unavailable state passed.');
} finally { await browser.close(); }
